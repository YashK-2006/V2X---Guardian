"""

Train the multi-class misbehavior detector on data generated by the live pipeline.



    python -m ai.train_detector                 # default: 4 runs x 240 sim-seconds

    python -m ai.train_detector --runs 6 --duration 300



The simulator runs headless (SUMO if available, otherwise the mock traffic

model). Attacks of every type are launched and stopped at random on random

vehicles; every transmitted message yields one labelled feature vector

(label = ground-truth attack type or "normal").



Two models are trained (RandomForest and XGBoost / GradientBoosting fallback),

evaluated on a held-out split, and the best (macro-F1) is saved to

ai/models/mbd_model.joblib together with ai/models/metrics.json.

"""



import argparse

import json

import logging

import os

import random

import time

from collections import Counter

from typing import Dict, List, Tuple



import numpy as np



from config import get_config

from ai.misbehavior_detector import FEATURE_NAMES



logger = logging.getLogger("train_detector")



TRAIN_SCENARIOS = ["normal", "high_traffic", "emergency_vehicle", "mixed"]





def collect(runs: int, duration: float, seed: int = 7) -> Tuple[np.ndarray, np.ndarray]:

    from backend.orchestrator import SimulationOrchestrator

    from simulation.attacks import ATTACK_TYPES



    cfg = get_config()

    rng = random.Random(seed)

    samples: List = []

    for run in range(runs):

        scenario = TRAIN_SCENARIOS[run % len(TRAIN_SCENARIOS)]

        orch = SimulationOrchestrator(cfg)

        orch.detector.model = None  # features must not depend on a previous model

        orch.record_replay = orch.persist_runs = False

        orch.setup(scenario)

        orch.scenario.attacks = []  # attacks are driven by this script

        orch.start()

        orch.sample_sink = samples

        steps = int(duration / cfg.simulation.step_length)

        t0 = time.time()

        for step in range(steps):

            orch.step()

            if step > 100 and step % 60 == 0:

                if rng.random() < 0.7:

                    try:

                        orch.launch_attack(None, rng.choice(list(ATTACK_TYPES)))

                    except ValueError:

                        pass

                for vid in list(orch.attacks.active):

                    if orch.sim_time - orch.attacks.active[vid].started_at > rng.uniform(15, 40):

                        orch.stop_attack(vid)

        orch.shutdown()

        logger.info("run %d (%s): %d samples total, %.1fs", run + 1, scenario, len(samples), time.time() - t0)



    X = np.array([s[0] for s in samples], dtype=float)

    y = np.array([s[1] for s in samples])

    return X, y





def balance(X: np.ndarray, y: np.ndarray, cap: Dict[str, int], seed: int = 0) -> Tuple[np.ndarray, np.ndarray]:

    rng = np.random.default_rng(seed)

    keep = []

    for label in np.unique(y):

        idx = np.nonzero(y == label)[0]

        limit = cap.get(label, cap.get("*", len(idx)))

        if len(idx) > limit:

            idx = rng.choice(idx, limit, replace=False)

        keep.extend(idx.tolist())

    keep = np.array(sorted(keep))

    return X[keep], y[keep]





def evaluate(name: str, model, classes: List[str], X_test, y_test, train_s: float) -> Dict:

    from sklearn.metrics import accuracy_score, precision_recall_fscore_support, confusion_matrix, classification_report



    t0 = time.perf_counter()

    proba = model.predict_proba(X_test)

    infer_ms = (time.perf_counter() - t0) * 1000 / len(X_test)

    pred = np.array([classes[i] for i in proba.argmax(axis=1)])



    bin_true = y_test != "normal"

    bin_pred = pred != "normal"

    tp = int(np.sum(bin_true & bin_pred))

    fp = int(np.sum(~bin_true & bin_pred))

    fn = int(np.sum(bin_true & ~bin_pred))

    tn = int(np.sum(~bin_true & ~bin_pred))

    p, r, f1, _ = precision_recall_fscore_support(y_test, pred, average="macro", zero_division=0)

    report = classification_report(y_test, pred, output_dict=True, zero_division=0)

    cm = confusion_matrix(y_test, pred, labels=classes)

    single = X_test[:1]

    t1 = time.perf_counter()

    for _ in range(50):

        model.predict_proba(single)

    single_ms = (time.perf_counter() - t1) * 1000 / 50



    return {

        "model": name,

        "accuracy": float(accuracy_score(y_test, pred)),

        "macro_precision": float(p), "macro_recall": float(r), "macro_f1": float(f1),

        "binary": {

            "precision": tp / (tp + fp) if tp + fp else 1.0,

            "recall": tp / (tp + fn) if tp + fn else 1.0,

            "f1": (2 * tp / (2 * tp + fp + fn)) if tp else 0.0,

            "false_positive_rate": fp / (fp + tn) if fp + tn else 0.0,

            "tp": tp, "fp": fp, "fn": fn, "tn": tn,

        },

        "per_class": {c: {k: float(v) for k, v in report[c].items()} for c in classes if c in report},

        "confusion_matrix": {"labels": classes, "matrix": cm.tolist()},

        "inference_ms_per_sample_batch": infer_ms,

        "inference_ms_single": single_ms,

        "training_time_s": train_s,

    }





def main():

    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)

    parser.add_argument("--runs", type=int, default=4)

    parser.add_argument("--duration", type=float, default=240.0, help="sim seconds per run")

    parser.add_argument("--out", default=get_config().ai.model_dir)

    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(message)s")

    for noisy in ("backend.orchestrator", "simulation", "ai.misbehavior_detector"):

        logging.getLogger(noisy).setLevel(logging.ERROR)



    from sklearn.ensemble import RandomForestClassifier

    from sklearn.model_selection import train_test_split



    X, y = collect(args.runs, args.duration)

    logger.info("collected %d samples: %s", len(y), dict(Counter(y)))

    X, y = balance(X, y, {"normal": 40000, "message_flooding": 4000, "revoked_identity": 4000, "*": 6000})

    logger.info("balanced to %d samples: %s", len(y), dict(Counter(y)))



    X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.25, stratify=y, random_state=42)

    classes = sorted(np.unique(y).tolist())



    candidates = []

    t0 = time.time()

    rf = RandomForestClassifier(n_estimators=80, max_depth=18, min_samples_leaf=2, class_weight="balanced",

                                n_jobs=-1, random_state=42)

    rf.fit(X_train, y_train)

    rf.set_params(n_jobs=1)  # single-threaded inference is faster for small live batches

    candidates.append(("random_forest", rf, list(rf.classes_), time.time() - t0))



    try:

        from xgboost import XGBClassifier

        label_idx = {c: i for i, c in enumerate(classes)}

        t0 = time.time()

        xgb = XGBClassifier(n_estimators=150, max_depth=6, learning_rate=0.15, subsample=0.9,

                            tree_method="hist", n_jobs=4, random_state=42)

        xgb.fit(X_train, np.array([label_idx[c] for c in y_train]))

        candidates.append(("xgboost", xgb, classes, time.time() - t0))

    except Exception as e:  # pragma: no cover - xgboost optional

        logger.warning("XGBoost unavailable (%s); training GradientBoosting instead", e)

        from sklearn.ensemble import HistGradientBoostingClassifier

        t0 = time.time()

        gb = HistGradientBoostingClassifier(max_iter=200, random_state=42)

        gb.fit(X_train, y_train)

        candidates.append(("gradient_boosting", gb, list(gb.classes_), time.time() - t0))



    results = []

    for name, model, model_classes, train_s in candidates:

        m = evaluate(name, model, model_classes, X_test, y_test, train_s)

        results.append((m, name, model, model_classes))

        logger.info("%-15s acc=%.4f macroF1=%.4f binF1=%.4f FPR=%.4f  %.3f ms/sample",

                    name, m["accuracy"], m["macro_f1"], m["binary"]["f1"], m["binary"]["false_positive_rate"],

                    m["inference_ms_single"])



    best_m, best_name, best_model, best_classes = max(results, key=lambda r: r[0]["macro_f1"])

    importances = {}

    if hasattr(best_model, "feature_importances_"):

        importances = {n: float(v) for n, v in zip(FEATURE_NAMES, best_model.feature_importances_)}



    os.makedirs(args.out, exist_ok=True)

    import joblib

    joblib.dump({"model": best_model, "classes": best_classes, "features": FEATURE_NAMES, "name": best_name,

                 "feature_importances": importances}, os.path.join(args.out, "mbd_model.joblib"))

    metrics = {

        "selected_model": best_name,

        "trained_at": time.strftime("%Y-%m-%d %H:%M:%S"),

        "dataset": {"samples": int(len(y)), "train": int(len(y_train)), "test": int(len(y_test)),

                    "class_counts": {k: int(v) for k, v in Counter(y).items()},

                    "runs": args.runs, "sim_seconds_per_run": args.duration},

        "features": FEATURE_NAMES,

        "feature_importances": dict(sorted(importances.items(), key=lambda kv: -kv[1])),

        "models": [r[0] for r in results],

    }

    with open(os.path.join(args.out, "metrics.json"), "w") as fh:

        json.dump(metrics, fh, indent=2)

    logger.info("saved %s model and metrics to %s", best_name, args.out)





if __name__ == "__main__":

    main()
